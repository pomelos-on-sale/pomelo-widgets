//! Application metadata shared between sub-apps and system launchers.

use core::time::Duration;
use iced::Color;
use pomelo_material_symbols::Icon;

use crate::preferences::{Language, SystemPreferences, ThemeMode};

/// Trait for applications that support querying and synchronizing system preferences.
pub trait AppPreferences {
    /// Returns the current system preferences.
    fn preferences(&self) -> SystemPreferences;

    /// Updates the application with new system preferences.
    fn set_preferences(&mut self, preferences: SystemPreferences);

    /// Returns the current theme mode.
    fn theme_mode(&self) -> ThemeMode {
        self.preferences().theme
    }

    /// Returns the current system language.
    fn language(&self) -> Language {
        self.preferences().language
    }
}

/// Creates an asynchronous stream that yields an item generated by `produce` at every `interval`.
///
/// Spawns a dedicated background timer thread that automatically terminates when the receiver stream is dropped.
/// If the UI thread is busy and the channel buffer fills up, new ticks are dropped rather than killing
/// the background worker thread.
pub fn interval_stream<T: Send + 'static>(
    name: &'static str,
    interval: Duration,
    mut produce: impl FnMut() -> T + Send + 'static,
) -> impl iced::futures::Stream<Item = T> {
    let (mut tx, rx) = iced::futures::channel::mpsc::channel(4);
    std::thread::Builder::new()
        .name(name.into())
        .spawn(move || {
            loop {
                std::thread::sleep(interval);
                let item = produce();
                if let Err(e) = tx.try_send(item) {
                    if e.is_disconnected() {
                        break;
                    }
                }
            }
        })
        .ok();
    rx
}


/// A baked bitmap icon, with 16-bit RGB565 color pixels and an 8-bit alpha mask.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BitmapIcon {
    /// Width in pixels.
    pub width: u16,
    /// Height in pixels.
    pub height: u16,
    /// Little-endian 16-bit RGB565 pixels (`width * height` entries).
    pub rgb565: &'static [u16],
    /// 8-bit alpha mask (`width * height` entries, 0 = transparent, 255 = opaque).
    pub alpha: &'static [u8],
}

impl BitmapIcon {
    /// Constructs a new [`BitmapIcon`].
    pub const fn new(
        width: u16,
        height: u16,
        rgb565: &'static [u16],
        alpha: &'static [u8],
    ) -> Self {
        Self {
            width,
            height,
            rgb565,
            alpha,
        }
    }
}

/// An application icon: either a vector glyph (Material Symbol), a pre-baked bitmap, or a QOI compressed image.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AppIcon {
    /// A vector glyph from Material Symbols.
    Glyph(Icon),
    /// A hardware-native RGB565 + Alpha bitmap icon.
    Bitmap(BitmapIcon),
    /// A Quite OK Image (QOI) compressed asset bytes (e.g. 118x118 RGBA with pre-applied squircle AA mask).
    Qoi(&'static [u8]),
}

impl AppIcon {
    /// Constructs a glyph application icon.
    pub const fn glyph(icon: Icon) -> Self {
        Self::Glyph(icon)
    }

    /// Constructs a bitmap application icon.
    pub const fn bitmap(
        width: u16,
        height: u16,
        rgb565: &'static [u16],
        alpha: &'static [u8],
    ) -> Self {
        Self::Bitmap(BitmapIcon::new(width, height, rgb565, alpha))
    }

    /// Constructs a QOI compressed application icon.
    pub const fn qoi(data: &'static [u8]) -> Self {
        Self::Qoi(data)
    }

    /// Returns the icon glyph if this is a [`AppIcon::Glyph`].
    pub const fn as_glyph(&self) -> Option<Icon> {
        match self {
            Self::Glyph(icon) => Some(*icon),
            _ => None,
        }
    }

    /// Returns the bitmap icon if this is a [`AppIcon::Bitmap`].
    pub const fn as_bitmap(&self) -> Option<BitmapIcon> {
        match self {
            Self::Bitmap(b) => Some(*b),
            _ => None,
        }
    }

    /// Returns the QOI bytes if this is a [`AppIcon::Qoi`].
    pub const fn as_qoi(&self) -> Option<&'static [u8]> {
        match self {
            Self::Qoi(data) => Some(data),
            _ => None,
        }
    }

    /// Whether this icon is a bitmap or QOI image.
    pub const fn is_bitmap(&self) -> bool {
        matches!(self, Self::Bitmap(_) | Self::Qoi(_))
    }
}

impl From<Icon> for AppIcon {
    fn from(icon: Icon) -> Self {
        Self::Glyph(icon)
    }
}

impl From<BitmapIcon> for AppIcon {
    fn from(bitmap: BitmapIcon) -> Self {
        Self::Bitmap(bitmap)
    }
}

/// Metadata describing an application's identity in the launcher and shell.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AppMeta {
    /// Shown under the tile (canonical English name).
    pub name: &'static str,
    /// Simplified Chinese name.
    pub name_zh: &'static str,
    /// Drawn inside the tile (glyph or bitmap).
    pub icon: AppIcon,
    /// The tile's accent, as RGB bytes so this table stays a plain `const`.
    pub accent: (u8, u8, u8),
}

impl AppMeta {
    /// Constructs a new [`AppMeta`] with the given names, icon, and accent color.
    pub const fn new(
        name: &'static str,
        name_zh: &'static str,
        icon: AppIcon,
        accent: (u8, u8, u8),
    ) -> Self {
        Self {
            name,
            name_zh,
            icon,
            accent,
        }
    }

    /// Constructs a new [`AppMeta`] with a glyph icon.
    pub const fn new_with_glyph(
        name: &'static str,
        name_zh: &'static str,
        icon: Icon,
        accent: (u8, u8, u8),
    ) -> Self {
        Self {
            name,
            name_zh,
            icon: AppIcon::Glyph(icon),
            accent,
        }
    }

    /// The localized name in `language`.
    pub const fn localized_name(&self, language: Language) -> &'static str {
        match language {
            Language::Chinese => self.name_zh,
            Language::English => self.name,
        }
    }

    /// Canonical English name.
    pub const fn name_en(&self) -> &'static str {
        self.name
    }

    /// The accent, as an iced [`Color`].
    pub fn color(&self) -> Color {
        let (r, g, b) = self.accent;
        Color::from_rgb8(r, g, b)
    }
}
